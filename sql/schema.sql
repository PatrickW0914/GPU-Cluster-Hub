-- Reservations and jobs

-- "Books": a reservation is made by a (user, group) MEMBERSHIP 
CREATE TABLE reservation (
    reservation_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         INTEGER      NOT NULL,
    group_id        INTEGER      NOT NULL,
    start_time      TIMESTAMP    NOT NULL,
    end_time        TIMESTAMP    NOT NULL,
    purpose         VARCHAR(200) NOT NULL,
    res_status      VARCHAR(10)  NOT NULL DEFAULT 'PENDING',
    created_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_res_membership FOREIGN KEY (user_id, group_id)
        REFERENCES membership (user_id, group_id) ON DELETE RESTRICT,
    CONSTRAINT ck_res_window   CHECK (end_time > start_time),
    CONSTRAINT ck_res_maxlen   CHECK (end_time - start_time <= INTERVAL '72 hours'),
    CONSTRAINT ck_res_status   CHECK (res_status IN
        ('PENDING','CONFIRMED','ACTIVE','COMPLETED','CANCELLED')),
    CONSTRAINT ck_res_created  CHECK (created_at <= start_time + INTERVAL '1 hour')
);

-- "Reserves" (M:N reservation <-> gpu)
CREATE TABLE reservation_gpu (
    reservation_id  INTEGER NOT NULL,
    gpu_id          INTEGER NOT NULL,
    CONSTRAINT pk_reservation_gpu PRIMARY KEY (reservation_id, gpu_id),
    CONSTRAINT fk_rg_reservation FOREIGN KEY (reservation_id)
        REFERENCES reservation (reservation_id) ON DELETE CASCADE,
    CONSTRAINT fk_rg_gpu FOREIGN KEY (gpu_id)
        REFERENCES gpu (gpu_id) ON DELETE RESTRICT
);

-- Job: "RunsUnder" (reservation 1:N job) 
-- "RunsIn" (env 1:N job)
CREATE TABLE job (
    job_id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id    INTEGER      NOT NULL,
    env_id            INTEGER      NOT NULL,
    job_name          VARCHAR(100) NOT NULL,
    submit_time       TIMESTAMP    NOT NULL,
    start_time        TIMESTAMP,
    end_time          TIMESTAMP,
    job_state         VARCHAR(10)  NOT NULL DEFAULT 'QUEUED',
    exit_code         SMALLINT,
    peak_vram_gb      NUMERIC(6,1),
    avg_gpu_util_pct  NUMERIC(5,2),
    CONSTRAINT fk_job_reservation FOREIGN KEY (reservation_id)
        REFERENCES reservation (reservation_id) ON DELETE RESTRICT,
    CONSTRAINT fk_job_env FOREIGN KEY (env_id)
        REFERENCES software_env (env_id) ON DELETE RESTRICT,
    CONSTRAINT ck_job_state CHECK (job_state IN
        ('QUEUED','RUNNING','COMPLETED','FAILED','CANCELLED','TIMEOUT')),
    CONSTRAINT ck_job_start CHECK (start_time IS NULL OR start_time >= submit_time),
    CONSTRAINT ck_job_end   CHECK (end_time IS NULL OR (start_time IS NOT NULL AND end_time >= start_time)),
    -- state must agree with which timestamps are present
    CONSTRAINT ck_job_state_times CHECK (
           (job_state = 'QUEUED'    AND start_time IS NULL AND end_time IS NULL)
        OR (job_state = 'RUNNING'   AND start_time IS NOT NULL AND end_time IS NULL)
        OR (job_state IN ('COMPLETED','FAILED','TIMEOUT')
                                    AND start_time IS NOT NULL AND end_time IS NOT NULL)
        OR (job_state = 'CANCELLED')),
    CONSTRAINT ck_job_exit CHECK (
        (job_state = 'COMPLETED' AND exit_code = 0)
     OR (job_state = 'FAILED'    AND exit_code <> 0)
     OR (job_state NOT IN ('COMPLETED','FAILED'))),
    CONSTRAINT ck_job_vram CHECK (peak_vram_gb IS NULL OR peak_vram_gb >= 0),
    CONSTRAINT ck_job_util CHECK (avg_gpu_util_pct IS NULL OR avg_gpu_util_pct BETWEEN 0 AND 100)
);

-- "Loads" (M:N job <-> model_version) 
CREATE TABLE job_loads_version (
    job_id       BIGINT      NOT NULL,
    model_id     INTEGER     NOT NULL,
    version_tag  VARCHAR(30) NOT NULL,
    usage_role   VARCHAR(12) NOT NULL,
    CONSTRAINT pk_job_loads PRIMARY KEY (job_id, model_id, version_tag),
    CONSTRAINT fk_jl_job FOREIGN KEY (job_id)
        REFERENCES job (job_id) ON DELETE CASCADE,
    CONSTRAINT fk_jl_version FOREIGN KEY (model_id, version_tag)
        REFERENCES model_version (model_id, version_tag)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT ck_jl_role CHECK (usage_role IN
        ('inference','fine-tune','pretrain','evaluation','attack','distillation'))
);
