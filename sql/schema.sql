CREATE TABLE cluster_user (
    user_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    net_id      VARCHAR(20)  NOT NULL,
    full_name   VARCHAR(80)  NOT NULL,
    email       VARCHAR(120) NOT NULL,
    user_role   VARCHAR(10)  NOT NULL,
    is_admin    BOOLEAN      NOT NULL DEFAULT FALSE,
    is_active   BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_user_netid  UNIQUE (net_id),
    CONSTRAINT uq_user_email  UNIQUE (email),
    CONSTRAINT ck_user_netid  CHECK (net_id ~ '^[a-z][a-z0-9]{2,19}$'),
    CONSTRAINT ck_user_email  CHECK (email ~ '^[^@\s]+@[^@\s]+\.[a-z]{2,}$'),
    CONSTRAINT ck_user_role   CHECK (user_role IN
        ('Faculty','Postdoc','PhD','MS','Undergrad','Staff'))
);

CREATE TABLE research_group (
    group_id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_name             VARCHAR(80)  NOT NULL,
    department             VARCHAR(60)  NOT NULL,
    pi_user_id             INTEGER      NOT NULL,     
    weekly_gpu_hour_quota  NUMERIC(7,1) NOT NULL,
    created_on             DATE         NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT uq_group_name  UNIQUE (group_name),
    CONSTRAINT ck_group_quota CHECK (weekly_gpu_hour_quota > 0
                                     AND weekly_gpu_hour_quota <= 10000)
    
);

CREATE TABLE membership (
    user_id      INTEGER     NOT NULL,
    group_id     INTEGER     NOT NULL,
    member_role  VARCHAR(12) NOT NULL DEFAULT 'Member',
    joined_on    DATE        NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT pk_membership PRIMARY KEY (user_id, group_id),
    CONSTRAINT fk_mem_user  FOREIGN KEY (user_id)
        REFERENCES cluster_user (user_id)   ON DELETE CASCADE,
    CONSTRAINT fk_mem_group FOREIGN KEY (group_id)
        REFERENCES research_group (group_id) ON DELETE CASCADE,
    CONSTRAINT ck_mem_role  CHECK (member_role IN ('Member','Collaborator','Manager'))
);

