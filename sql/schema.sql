CREATE TABLE compute_node (
    node_id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hostname          VARCHAR(40)  NOT NULL,
    partition_name    VARCHAR(12)  NOT NULL,
    cpu_cores         SMALLINT     NOT NULL,
    ram_gb            INTEGER      NOT NULL,
    local_nvme_tb     NUMERIC(5,2) NOT NULL,
    max_cuda_version  NUMERIC(4,1) NOT NULL, 
    node_status       VARCHAR(6)   NOT NULL DEFAULT 'UP',
    rack_location     VARCHAR(10),
    CONSTRAINT uq_node_hostname  UNIQUE (hostname),
    CONSTRAINT ck_node_partition CHECK (partition_name IN ('gpu','gpu-long','gpu-short','debug')),
    CONSTRAINT ck_node_cpu       CHECK (cpu_cores BETWEEN 1 AND 512),
    CONSTRAINT ck_node_ram       CHECK (ram_gb BETWEEN 1 AND 8192),
    CONSTRAINT ck_node_nvme      CHECK (local_nvme_tb >= 0),
    CONSTRAINT ck_node_cuda      CHECK (max_cuda_version BETWEEN 9.0 AND 20.0),
    CONSTRAINT ck_node_status    CHECK (node_status IN ('UP','DRAIN','DOWN'))
);

CREATE TABLE gpu_type (
    gpu_type_id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_name           VARCHAR(40)  NOT NULL,
    vendor              VARCHAR(10)  NOT NULL,
    architecture        VARCHAR(20)  NOT NULL,
    vram_gb             SMALLINT     NOT NULL,
    compute_capability  NUMERIC(3,1) NOT NULL,
    fp16_tflops         NUMERIC(7,1) NOT NULL,   
    supports_bf16       BOOLEAN      NOT NULL,
    CONSTRAINT uq_gputype_name  UNIQUE (type_name),
    CONSTRAINT ck_gputype_vendor CHECK (vendor IN ('NVIDIA','AMD')),
    CONSTRAINT ck_gputype_vram  CHECK (vram_gb > 0),
    CONSTRAINT ck_gputype_cc    CHECK (compute_capability > 0),
    CONSTRAINT ck_gputype_tflops CHECK (fp16_tflops > 0)
);


CREATE TABLE gpu (
    gpu_id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    node_id        INTEGER     NOT NULL,
    slot_index     SMALLINT    NOT NULL,
    gpu_type_id    INTEGER     NOT NULL,
    serial_number  VARCHAR(30) NOT NULL,
    gpu_status     VARCHAR(12) NOT NULL DEFAULT 'AVAILABLE',
    installed_on   DATE        NOT NULL,
    CONSTRAINT uq_gpu_serial     UNIQUE (serial_number),
    CONSTRAINT uq_gpu_node_slot  UNIQUE (node_id, slot_index),
    CONSTRAINT fk_gpu_node FOREIGN KEY (node_id)
        REFERENCES compute_node (node_id) ON DELETE RESTRICT,
    CONSTRAINT fk_gpu_type FOREIGN KEY (gpu_type_id)
        REFERENCES gpu_type (gpu_type_id) ON DELETE RESTRICT,
    CONSTRAINT ck_gpu_slot   CHECK (slot_index BETWEEN 0 AND 15),
    CONSTRAINT ck_gpu_status CHECK (gpu_status IN ('AVAILABLE','MAINTENANCE','RETIRED'))
);

-- Models, checkpoints, environments

CREATE TABLE ai_model (
    model_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_name     VARCHAR(60)  NOT NULL,
    task_category  VARCHAR(12)  NOT NULL,
    framework      VARCHAR(12)  NOT NULL,
    license        VARCHAR(40)  NOT NULL,
    source_url     VARCHAR(200),
    maintainer_id  INTEGER      NOT NULL,      
    description    TEXT,
    added_on       DATE         NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT uq_model_name UNIQUE (model_name),
    CONSTRAINT fk_model_maintainer FOREIGN KEY (maintainer_id)
        REFERENCES cluster_user (user_id) ON DELETE RESTRICT,
    CONSTRAINT ck_model_task CHECK (task_category IN
        ('LLM','Vision','Diffusion','Audio','Multimodal','Detection','Other')),
    CONSTRAINT ck_model_framework CHECK (framework IN ('PyTorch','JAX','TensorFlow','ONNX')),
    CONSTRAINT ck_model_url CHECK (source_url IS NULL OR source_url ~ '^https?://')
);

-- Weak entity: a version (checkpoint) is identified by its model and version_tag.
CREATE TABLE model_version (
    model_id            INTEGER      NOT NULL,
    version_tag         VARCHAR(30)  NOT NULL,   
    param_count_b       NUMERIC(8,3) NOT NULL,   
    weight_precision    VARCHAR(5)   NOT NULL,
    min_vram_gb         NUMERIC(6,1) NOT NULL,   
    checkpoint_size_gb  NUMERIC(8,2) NOT NULL,
    released_on         DATE,
    is_deprecated       BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT pk_model_version PRIMARY KEY (model_id, version_tag),
    CONSTRAINT fk_mv_model FOREIGN KEY (model_id)
        REFERENCES ai_model (model_id) ON DELETE CASCADE,
    CONSTRAINT ck_mv_params    CHECK (param_count_b > 0),
    CONSTRAINT ck_mv_precision CHECK (weight_precision IN ('fp32','fp16','bf16','int8','int4')),
    CONSTRAINT ck_mv_vram      CHECK (min_vram_gb > 0),
    CONSTRAINT ck_mv_size      CHECK (checkpoint_size_gb > 0)
);

