-- a group's PI must be a Faculty user --
CREATE FUNCTION trg_group_pi_is_faculty() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM cluster_user
                   WHERE user_id = NEW.pi_user_id AND user_role = 'Faculty') THEN
        RAISE EXCEPTION 'PI (user %) of group "%" must have role Faculty',
                        NEW.pi_user_id, NEW.group_name
              USING ERRCODE = 'GH008';
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER group_pi_is_faculty
    BEFORE INSERT OR UPDATE OF pi_user_id ON research_group
    FOR EACH ROW EXECUTE FUNCTION trg_group_pi_is_faculty();

CREATE FUNCTION trg_user_role_keeps_pi() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.user_role <> 'Faculty'
       AND EXISTS (SELECT 1 FROM research_group WHERE pi_user_id = NEW.user_id) THEN
        RAISE EXCEPTION 'User % is the PI of a group and must remain Faculty', NEW.user_id
              USING ERRCODE = 'GH008';
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER user_role_keeps_pi
    BEFORE UPDATE OF user_role ON cluster_user
    FOR EACH ROW EXECUTE FUNCTION trg_user_role_keeps_pi();

-- R2-R4: GPU booking rules (no double booking, GPU must be bookable,
--        group weekly quota).  
CREATE FUNCTION check_reservation(p_res_id INTEGER) RETURNS void
LANGUAGE plpgsql AS $$
DECLARE
    r          reservation%ROWTYPE;
    v_gpu      INTEGER;
    v_clash    INTEGER;
    v_quota    NUMERIC;
    v_used     NUMERIC;
BEGIN
    SELECT * INTO r FROM reservation WHERE reservation_id = p_res_id;
    IF NOT FOUND OR r.res_status = 'CANCELLED' THEN
        RETURN;                         
    END IF;

    -- Translating concurrent bookings for the same group and the same GPUs.
    PERFORM 1 FROM research_group WHERE group_id = r.group_id FOR UPDATE;
    PERFORM 1 FROM gpu g JOIN reservation_gpu rg ON rg.gpu_id = g.gpu_id
     WHERE rg.reservation_id = p_res_id ORDER BY g.gpu_id FOR UPDATE OF g;

    FOR v_gpu IN SELECT gpu_id FROM reservation_gpu WHERE reservation_id = p_res_id LOOP
        SELECT o.reservation_id INTO v_clash
          FROM reservation_gpu og
          JOIN reservation o ON o.reservation_id = og.reservation_id
         WHERE og.gpu_id = v_gpu
           AND o.reservation_id <> p_res_id
           AND o.res_status <> 'CANCELLED'
           AND tsrange(o.start_time, o.end_time) && tsrange(r.start_time, r.end_time)
         LIMIT 1;
        IF FOUND THEN
            RAISE EXCEPTION 'GPU % is already booked by reservation % during % - %',
                  v_gpu, v_clash, r.start_time, r.end_time
                  USING ERRCODE = 'GH001';
        END IF;

        IF r.res_status IN ('PENDING','CONFIRMED') AND EXISTS (
               SELECT 1 FROM gpu g JOIN compute_node n ON n.node_id = g.node_id
                WHERE g.gpu_id = v_gpu
                  AND (g.gpu_status <> 'AVAILABLE' OR n.node_status <> 'UP')) THEN
            RAISE EXCEPTION 'GPU % is not available for booking (maintenance, retired, or node not UP)', v_gpu
                  USING ERRCODE = 'GH002';
        END IF;
    END LOOP;

    SELECT weekly_gpu_hour_quota INTO v_quota
      FROM research_group WHERE group_id = r.group_id;

    SELECT COALESCE(SUM(EXTRACT(EPOCH FROM (o.end_time - o.start_time)) / 3600.0), 0)
      INTO v_used
      FROM reservation o
      JOIN reservation_gpu og ON og.reservation_id = o.reservation_id
     WHERE o.group_id = r.group_id
       AND o.res_status <> 'CANCELLED'
       AND o.start_time >= date_trunc('week', r.start_time)
       AND o.start_time <  date_trunc('week', r.start_time) + INTERVAL '7 days';

    IF v_used > v_quota THEN
        RAISE EXCEPTION 'Group % would use % GPU-hours in week of %, quota is %',
              r.group_id, round(v_used, 1), date_trunc('week', r.start_time)::date, v_quota
              USING ERRCODE = 'GH003';
    END IF;
END $$;

-- Reservation GPU-hours 
CREATE VIEW v_reservation_hours AS
SELECT r.reservation_id, r.user_id, r.group_id, r.start_time, r.end_time, r.res_status,
       COUNT(rg.gpu_id)                                              AS gpu_count,
       COUNT(rg.gpu_id) * EXTRACT(EPOCH FROM (r.end_time - r.start_time)) / 3600.0
                                                                     AS gpu_hours
  FROM reservation r
  LEFT JOIN reservation_gpu rg ON rg.reservation_id = r.reservation_id
 GROUP BY r.reservation_id;

