-- Every reservation holds at least one GPU 
CREATE FUNCTION trg_reservation_has_gpu() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_res INTEGER := CASE WHEN TG_TABLE_NAME = 'reservation'
                          THEN NEW.reservation_id ELSE OLD.reservation_id END;
BEGIN
    IF EXISTS (SELECT 1 FROM reservation WHERE reservation_id = v_res)
       AND NOT EXISTS (SELECT 1 FROM reservation_gpu WHERE reservation_id = v_res) THEN
        RAISE EXCEPTION 'Reservation % must include at least one GPU', v_res
              USING ERRCODE = 'GH004';
    END IF;
    RETURN NULL;
END $$;

CREATE CONSTRAINT TRIGGER reservation_has_gpu
    AFTER INSERT ON reservation
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION trg_reservation_has_gpu();

CREATE CONSTRAINT TRIGGER reservation_keeps_gpu
    AFTER DELETE OR UPDATE ON reservation_gpu
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION trg_reservation_has_gpu();

-- A job runs inside its reservation's window and never under a
--     cancelled reservation.
CREATE FUNCTION trg_job_in_window() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    r reservation%ROWTYPE;
BEGIN
    SELECT * INTO r FROM reservation WHERE reservation_id = NEW.reservation_id;
    IF r.res_status = 'CANCELLED' AND NEW.job_state NOT IN ('CANCELLED') THEN
        RAISE EXCEPTION 'Reservation % is cancelled; job "%" cannot run under it',
              r.reservation_id, NEW.job_name USING ERRCODE = 'GH005';
    END IF;
    IF NEW.start_time IS NOT NULL
       AND (NEW.start_time < r.start_time OR NEW.start_time >= r.end_time) THEN
        RAISE EXCEPTION 'Job "%" starts at %, outside reservation % window [% , %)',
              NEW.job_name, NEW.start_time, r.reservation_id, r.start_time, r.end_time
              USING ERRCODE = 'GH005';
    END IF;
    IF NEW.end_time IS NOT NULL AND NEW.end_time > r.end_time THEN
        RAISE EXCEPTION 'Job "%" ends at %, after reservation % ends at %',
              NEW.job_name, NEW.end_time, r.reservation_id, r.end_time
              USING ERRCODE = 'GH005';
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER job_in_window
    BEFORE INSERT OR UPDATE OF reservation_id, start_time, end_time, job_state ON job
    FOR EACH ROW EXECUTE FUNCTION trg_job_in_window();

-- a job may only load model versions verified for the job's environment
CREATE FUNCTION trg_job_load_compatible() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_env INTEGER;
BEGIN
    SELECT env_id INTO v_env FROM job WHERE job_id = NEW.job_id;
    IF NOT EXISTS (SELECT 1 FROM env_supports_version
                    WHERE env_id = v_env
                      AND model_id = NEW.model_id
                      AND version_tag = NEW.version_tag) THEN
        RAISE EXCEPTION 'Model % version "%" is not verified for environment %',
              NEW.model_id, NEW.version_tag, v_env USING ERRCODE = 'GH006';
    END IF;
    RETURN NULL;
END $$;

-- A job may only load model versions verified for the job's environment
CREATE TRIGGER job_load_compatible
    AFTER INSERT OR UPDATE ON job_loads_version
    FOR EACH ROW EXECUTE FUNCTION trg_job_load_compatible();

-- If a job changes its environment, it must still be compatible with all the
-- model versions it loads.
CREATE FUNCTION trg_job_env_change() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM job_loads_version jl
                WHERE jl.job_id = NEW.job_id
                  AND NOT EXISTS (SELECT 1 FROM env_supports_version es
                                   WHERE es.env_id = NEW.env_id
                                     AND es.model_id = jl.model_id
                                     AND es.version_tag = jl.version_tag)) THEN
        RAISE EXCEPTION 'Environment % does not support every model version job % loads',
              NEW.env_id, NEW.job_id USING ERRCODE = 'GH006';
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER job_env_change
    BEFORE UPDATE OF env_id ON job
    FOR EACH ROW EXECUTE FUNCTION trg_job_env_change();

-- A node's total checkpoint size must not exceed its local NVMe capacity.
CREATE FUNCTION trg_node_storage_capacity() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_node   INTEGER := NEW.node_id;   -- both trigger tables have node_id
    v_used   NUMERIC;
    v_cap    NUMERIC;
BEGIN
    SELECT COALESCE(SUM(mv.checkpoint_size_gb), 0) INTO v_used
      FROM node_hosts_version h
      JOIN model_version mv USING (model_id, version_tag)
     WHERE h.node_id = v_node;
    SELECT local_nvme_tb * 1000 INTO v_cap FROM compute_node WHERE node_id = v_node;
    IF v_used > v_cap THEN
        RAISE EXCEPTION 'Node % would hold % GB of checkpoints, capacity is % GB',
              v_node, v_used, v_cap USING ERRCODE = 'GH007';
    END IF;
    RETURN NULL;
END $$;

CREATE TRIGGER hosts_storage_capacity
    AFTER INSERT OR UPDATE ON node_hosts_version
    FOR EACH ROW EXECUTE FUNCTION trg_node_storage_capacity();

CREATE TRIGGER node_storage_capacity
    AFTER UPDATE OF local_nvme_tb ON compute_node
    FOR EACH ROW EXECUTE FUNCTION trg_node_storage_capacity();

-- Convenience view used by the application
CREATE VIEW v_gpu_inventory AS
SELECT g.gpu_id, n.hostname, g.slot_index, t.type_name, t.vram_gb,
       t.compute_capability, t.fp16_tflops, g.gpu_status, n.node_status,
       n.partition_name, n.max_cuda_version, n.node_id, t.gpu_type_id
  FROM gpu g
  JOIN compute_node n ON n.node_id = g.node_id
  JOIN gpu_type t     ON t.gpu_type_id = g.gpu_type_id;

